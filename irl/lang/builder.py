"""The .irl compiler — 2.1 "Full Language Edition".

Pipeline:  source -> lexer -> parser -> IR (canonical AST) -> optimizer
passes -> Python source -> CPython bytecode (.pyc).

The optimizer runs constant folding, dead-code elimination, memo
lowering and builtin caching, and reports exactly what it did. The
Python back end is CPython's own compiler, so compiled programs run at
full CPython speed — and the emitted code does fewer bytecode
operations than naive Python thanks to the passes.
"""

