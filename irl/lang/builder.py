def compile_source(code, level=1, source_dir=None, report=None):
    """Transpile .irl source to Python source. Returns (py_source, report)."""
    report = report or {
        "constants_folded": 0,
        "dead_branches_removed": 0,
        "memoized_functions": 0,
    }
    program = parse(_lex(code))
    optimize(program, report, level)
    t = PyTranspiler(level=level)
    t.scope = Scope("global")
    if source_dir:
        t.local_source_dirs.append(source_dir)
    for stmt in program.statements:
        t.visit_stmt(stmt)
    py_source = t.finish()
    report["memoized_functions"] = len(t.memo_functions)
    return py_source, report


def build_file(path, args):
    """CLI entry: irl lang build <file.irl> [flags]."""
    from rich.console import Console

    console = Console()
    out = None
    run_after = "--run" in args
    verbose = "-v" in args or "--verbose" in args
    emit_py = "--emit-py" in args
    emit_ir = "--emit-ir" in args
    level = 1
    for arg in args:
        if arg in ("-O0", "-O1", "-O2"):
            level = int(arg[2:])

    if not os.path.exists(path):
        console.print(f"[red][IRL_BUILD_ERROR] {path}: file not found[/red]")
        return 1

    code = open(path, encoding="utf-8").read()
    source_dir = os.path.dirname(os.path.abspath(path))

    try:
        if emit_ir:
            program = parse(_lex(code))
            from rich.syntax import Syntax

            console.print(Syntax(repr(program)[:4000], "python", word_wrap=True))
            return 0
        py_source, report = compile_source(code, level=level, source_dir=source_dir)
    except IrlSyntaxError as exc:
        from irl.lang_runner import format_error

        console.print(f"[red]{format_error(exc, code)}[/red]")
        return 1
    except BuildError as exc:
        console.print(f"[red]{exc}[/red]")
        return 1

    if emit_py:
        console.print(py_source)
        return 0

    base = out or os.path.splitext(path)[0]
    py_path = base + ".py"
    pyc_path = base + ".pyc"

    cache_dir = os.path.join(source_dir, ".irl_cache")
    source_hash = hashlib.sha256((code + f"|O{level}").encode("utf-8")).hexdigest()
    cached_pyc = os.path.join(cache_dir, f"{source_hash}.pyc")

    try:
        os.makedirs(cache_dir, exist_ok=True)
        with open(py_path, "w", encoding="utf-8") as fh:
            fh.write(py_source)
        cache_hit = os.path.exists(cached_pyc)
        if not cache_hit:
            py_compile.compile(py_path, cfile=cached_pyc, doraise=True)
        py_compile.compile(py_path, cfile=pyc_path, doraise=True)
    except py_compile.PyCompileError as exc:
        console.print(f"[red][IRL_BUILD_ERROR] back-end compile failed: {exc}[/red]")
        return 1

    if verbose:
        console.print(
            f"[cyan]optimizer:[/cyan] folded {report['constants_folded']} constant(s), removed {report['dead_branches_removed']} dead branch(es), memoized {report['memoized_functions']} function(s)"
        )
    console.print(f"[green]built[/green] {pyc_path} [dim](-O{level}, {'cache hit' if cache_hit else 'fresh'})[/dim]")

    if run_after:
        result = subprocess.run([sys.executable, pyc_path])
        return result.returncode
    return 0
